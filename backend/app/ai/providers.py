"""Modular AI providers. External providers receive only retrieved excerpts, never whole documents."""
from __future__ import annotations

import json
import re
from abc import ABC, abstractmethod
from dataclasses import dataclass

import httpx

from ..config import get_settings
from ..rag.retriever import RetrievalHit, tokens


@dataclass
class GeneratedContent:
    question: str
    bloom_level: str
    difficulty: str
    rationale: str
    answer_key: str


class AIProvider(ABC):
    name = "base"

    @abstractmethod
    def generate_question(self, *, topic: str, unit: str, marks: int, question_type: str, difficulty: str, bloom: str, hits: list[RetrievalHit], variation: int = 0, style_hint: str | None = None) -> GeneratedContent:
        raise NotImplementedError

    @abstractmethod
    def validate_question(self, *, question: str, topic: str, unit: str, marks: int, source: str) -> dict:
        """Independent second pass. It must not silently approve unsupported claims."""
        raise NotImplementedError


class LocalGroundedProvider(AIProvider):
    """Transparent development fallback: deterministic source-to-question transformation, not simulated AI."""
    name = "local-grounded"

    STEMS = {
        "Remember": ["Define", "State", "List the key elements of"],
        "Understand": ["Explain", "Describe", "Summarize"],
        "Apply": ["Apply the principles of", "Demonstrate the use of", "Illustrate"],
        "Analyze": ["Analyze", "Differentiate the main elements of", "Examine"],
        "Evaluate": ["Evaluate", "Justify the significance of", "Critically discuss"],
        "Create": ["Design an approach using", "Develop a solution based on", "Construct a model using"],
    }

    def generate_question(self, *, topic: str, unit: str, marks: int, question_type: str, difficulty: str, bloom: str, hits: list[RetrievalHit], variation: int = 0, style_hint: str | None = None) -> GeneratedContent:
        if not hits:
            raise ValueError("Insufficient syllabus/reference information available to generate a reliable question for this requirement.")
        source = hits[0].chunk.content
        source_terms = [word for word in tokens(source) if word not in tokens(topic)]
        focus = list(dict.fromkeys(source_terms))[:4]
        stems = self.STEMS.get(bloom, self.STEMS["Understand"])
        safe_style = style_hint.capitalize() if style_hint and style_hint.lower() in {"explain", "define", "compare", "derive", "calculate", "write", "implement", "discuss", "analyze", "evaluate"} else None
        stem = safe_style or stems[variation % len(stems)]
        qtype = question_type.lower()
        if "program" in qtype or "code" in qtype or "debug" in qtype:
            qualifier = f" The solution must demonstrate {', '.join(focus[:2])}." if focus else ""
            question = f"{stem} a program or algorithm for {topic}, using only the concepts covered in {unit}.{qualifier}"
        elif "mcq" in qtype:
            # Local mode cannot safely invent distractors; ask a grounded selection task.
            question = f"Which statement best explains {topic} as presented in {unit}? State the selected statement and justify it briefly."
        elif marks <= 2:
            question = f"{stem} {topic} in the context of {unit}."
        elif marks <= 8:
            qualifier = f", including {', '.join(focus[:2])}" if focus else ""
            question = f"{stem} {topic}{qualifier}, as covered in {unit}."
        else:
            qualifier = f" Discuss {', '.join(focus[:3])} with suitable steps or examples from the prescribed material." if focus else " Support the answer with suitable steps or examples from the prescribed material."
            question = f"{stem} {topic} in detail.{qualifier}"
        question = re.sub(r"\s+", " ", question).strip()
        if not question.endswith(("?", ".")):
            question += "."
        sentences = [part.strip() for part in re.split(r"(?<=[.!?])\s+|\n", source) if len(part.strip()) > 20]
        answer = "Reference-based key points:\n" + "\n".join(f"• {sentence[:450]}" for sentence in sentences[:4])
        return GeneratedContent(
            question=question,
            bloom_level=bloom,
            difficulty=difficulty,
            rationale=f"Generated by the local grounded engine from the selected {unit} / {topic} source excerpt. No external model was used.",
            answer_key=answer,
        )

    def validate_question(self, *, question: str, topic: str, unit: str, marks: int, source: str) -> dict:
        # Local mode does not pretend to perform an AI correctness review. The deterministic
        # source/portion/duplicate/marks checks remain authoritative until a provider is configured.
        return {"available": False, "passed": None, "technically_correct": None, "note": "External AI validation is not configured; teacher technical review is required."}


class OpenAICompatibleProvider(AIProvider):
    name = "openai-compatible"

    def __init__(self):
        self.settings = get_settings()
        if not self.settings.ai_api_key:
            raise RuntimeError("AI_API_KEY is required when AI_PROVIDER is not 'local'.")

    def generate_question(self, *, topic: str, unit: str, marks: int, question_type: str, difficulty: str, bloom: str, hits: list[RetrievalHit], variation: int = 0, style_hint: str | None = None) -> GeneratedContent:
        allowed = "\n\n".join(
            f"SOURCE {i + 1} ({hit.document.original_name}, {hit.chunk.location}):\n{hit.chunk.content}"
            for i, hit in enumerate(hits[:4])
        )
        system = (
            "You are an academic question author. Use ONLY ALLOWED CONTENT. Do not add facts, topics, examples, "
            "formulae, or terminology absent from it. If evidence is insufficient, return an error field. Previous "
            "paper text is never allowed content. Return strict JSON with question, bloom_level, difficulty, rationale, "
            "answer_key. Rationale must be concise provenance, not hidden reasoning."
        )
        user = f"""Create one distinct, technically answerable examination question.
Unit: {unit}
Topic: {topic}
Marks: {marks}
Question type: {question_type}
Difficulty: {difficulty}
Bloom level: {bloom}
Variation: {variation}
Previous-paper style hint (format only): {style_hint or "none"}

ALLOWED CONTENT:
{allowed}
"""
        endpoint = self.settings.ai_base_url.rstrip("/") + "/chat/completions"
        try:
            response = httpx.post(
                endpoint,
                headers={"Authorization": f"Bearer {self.settings.ai_api_key}", "Content-Type": "application/json"},
                json={
                    "model": self.settings.ai_model,
                    "temperature": 0.25,
                    "response_format": {"type": "json_object"},
                    "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
                },
                timeout=60,
            )
            response.raise_for_status()
            payload = json.loads(response.json()["choices"][0]["message"]["content"])
        except (httpx.HTTPError, KeyError, ValueError, json.JSONDecodeError) as exc:
            raise RuntimeError("The configured AI provider failed to return a valid grounded question.") from exc
        if payload.get("error"):
            raise ValueError("Insufficient syllabus/reference information available to generate a reliable question for this requirement.")
        question = str(payload.get("question", "")).strip()
        if len(question) < 10:
            raise RuntimeError("The AI provider returned an empty question.")
        return GeneratedContent(
            question=question,
            bloom_level=str(payload.get("bloom_level", bloom)),
            difficulty=str(payload.get("difficulty", difficulty)),
            rationale=str(payload.get("rationale", "Grounded in retrieved selected-portion sources.")),
            answer_key=str(payload.get("answer_key", "")),
        )

    def validate_question(self, *, question: str, topic: str, unit: str, marks: int, source: str) -> dict:
        system = (
            "Independently validate one examination question against ONLY the supplied source. Return strict JSON "
            "with booleans inside_source, correct_unit_topic, answerable, technically_correct, marks_appropriate, "
            "and a short note. Never infer missing facts."
        )
        user = f"Unit: {unit}\nTopic: {topic}\nMarks: {marks}\nQuestion: {question}\n\nALLOWED SOURCE:\n{source}"
        try:
            response = httpx.post(
                self.settings.ai_base_url.rstrip("/") + "/chat/completions",
                headers={"Authorization": f"Bearer {self.settings.ai_api_key}", "Content-Type": "application/json"},
                json={
                    "model": self.settings.ai_model, "temperature": 0,
                    "response_format": {"type": "json_object"},
                    "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
                }, timeout=60,
            )
            response.raise_for_status()
            payload = json.loads(response.json()["choices"][0]["message"]["content"])
        except (httpx.HTTPError, KeyError, ValueError, json.JSONDecodeError) as exc:
            raise RuntimeError("The configured AI provider failed during the independent validation pass.") from exc
        checks = [payload.get(key) is True for key in ("inside_source", "correct_unit_topic", "answerable", "technically_correct", "marks_appropriate")]
        return {"available": True, "passed": all(checks), **payload}


def get_ai_provider() -> AIProvider:
    provider = get_settings().ai_provider.lower()
    if provider in {"local", "development", "mock"}:
        return LocalGroundedProvider()
    if provider in {"openai", "compatible", "openai-compatible"}:
        return OpenAICompatibleProvider()
    raise RuntimeError(f"Unsupported AI_PROVIDER: {provider}")
